# 加载 XML 并填入翻译
$xml = [xml](Get-Content "translations\qgc_source_zh_CN.ts" -Raw -Encoding UTF8)
$filledCount = 0
$notFound = [System.Collections.Generic.HashSet[string]]::new()
foreach ($ctx in $xml.TS.context) {
  $msgs = @($ctx.message)
  foreach ($m in $msgs) {
    if ($m.translation.type -eq 'unfinished') {
      $src = $m.source
      if ($translations.ContainsKey($src)) {
        $m.translation.InnerText = $translations[$src]
        $m.translation.RemoveAttribute('type')
        $filledCount++
      } else {
        [void]$notFound.Add($src)
      }
    }
  }
}
$xml.Save("translations\qgc_source_zh_CN.ts")
"Filled: $filledCount"
"Not found (still unfinished): $($notFound.Count)"
if ($notFound.Count -gt 0) { "Missing sources:"; $notFound | Sort-Object | Select-Object -First 20 }
